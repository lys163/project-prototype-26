CREATE TABLE reviews (
    id uuid NOT NULL,
    user_id uuid NOT NULL,
    book_id uuid NOT NULL,
    rating integer NOT NULL,
    content varchar(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT pk_reviews PRIMARY KEY (id),
    CONSTRAINT uq_reviews_user_book UNIQUE (user_id, book_id)
);

CREATE TABLE reports (
    id uuid NOT NULL,
    reporter_id uuid NOT NULL,
    book_id uuid NOT NULL,
    book_title varchar(255) NOT NULL,
    reason varchar(255) NOT NULL,
    detail varchar(500),
    status varchar(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT chk_reports_reason CHECK (reason IN ('SPAM', 'INAPPROPRIATE', 'COPYRIGHT', 'OTHER')),
    CONSTRAINT chk_reports_status CHECK (status IN ('PENDING', 'RESOLVED', 'DISMISSED'))
);

