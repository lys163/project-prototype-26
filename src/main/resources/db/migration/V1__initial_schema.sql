    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT pk_image_generation_logs PRIMARY KEY (id),
    CONSTRAINT chk_image_generation_logs_source_type CHECK (source_type IN ('AI_TEXT_GENERATED', 'AI_IMAGE_ANALYZED'))
